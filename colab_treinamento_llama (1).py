"""## Célula 3: Carregamento Automático do Dataset
Esta célula detecta automaticamente se você subiu `dataset_c_programacao.json` ou `dataset-organizado.txt`.
"""

import os
import json
import tarfile

NOME_ARQUIVO_DATASET = "dataset_c_programacao.json"
dados = None

# 1. Se houver arquivo .tar.gz enviado, extrai automaticamente
for f in os.listdir("."):
    if f.endswith(".tar.gz") or f.endswith(".tgz"):
        print(f"Arquivo compactado '{f}' detectado. Extraindo...")
        with tarfile.open(f, "r:gz") as tar:
            tar.extractall()

# 2. Se o arquivo JSON existir, carrega e limpa qualquer caractere extra no final
if os.path.exists("dataset_c_programacao.json"):
    print("Lendo 'dataset_c_programacao.json'...")
    with open("dataset_c_programacao.json", "r", encoding="utf-8", errors="ignore") as f:
        conteudo = f.read().strip()

    try:
        dados = json.loads(conteudo)
    except json.JSONDecodeError:
        print("Detectado caractere extra no final do arquivo. Corrigindo e limpando automaticamente...")
        fim = conteudo.rfind("]")
        while fim != -1:
            try:
                dados = json.loads(conteudo[:fim+1])
                break
            except json.JSONDecodeError:
                fim = conteudo.rfind("]", 0, fim)

# 3. Se não carregou o JSON mas tem o .txt original, converte na hora
if not dados and os.path.exists("dataset-organizado.txt"):
    print("Convertendo 'dataset-organizado.txt' original para JSON...")
    with open("dataset-organizado.txt", "r", encoding="utf-8", errors="ignore") as f:
        texto = f.read()

    blocos = texto.split("<human>:")
    dados = []
    for b in blocos[1:]:
        if "<bot>:" in b:
            partes = b.split("<bot>:", 1)
            dados.append({
                "instruction": partes[0].strip(),
                "input": "",
                "output": partes[1].strip()
            })

if not dados:
    raise FileNotFoundError(
        "Nenhum dataset encontrado! Por favor, arraste 'dataset_c_programacao.json' ou 'dataset-organizado.txt' "
        "para a aba lateral de arquivos do Colab."
    )

# Reescreve o arquivo 100% limpo e validado
with open(NOME_ARQUIVO_DATASET, "w", encoding="utf-8") as f:
    json.dump(dados, f, ensure_ascii=False, indent=2)

print(f"\n Sucesso! {len(dados)} exemplos carregados e validados em '{NOME_ARQUIVO_DATASET}'.")
