"""## Célula 4: Formatar Dataset com o Chat Template Oficial do LLaMA 3.2"""

from datasets import load_dataset
from transformers import AutoTokenizer

MODEL_ID = "meta-llama/Llama-3.2-1B-Instruct"

# 1. Carregar Tokenizer
tokenizer = AutoTokenizer.from_pretrained(MODEL_ID, trust_remote_code=True)
if tokenizer.pad_token is None:
    tokenizer.pad_token = tokenizer.eos_token
tokenizer.padding_side = "right"

# 2. Carregar o arquivo JSON como Dataset Hugging Face
dataset = load_dataset("json", data_files=NOME_ARQUIVO_DATASET, split="train")

# 3. Formatar de acordo com a sintaxe oficial de conversação do LLaMA 3.2
def format_prompts(batch):
    texts = []
    for instruction, input_text, output in zip(batch["instruction"], batch["input"], batch["output"]):
        user_content = f"{instruction}\n\n{input_text}" if input_text and input_text.strip() else instruction

        messages = [
            {"role": "user", "content": user_content},
            {"role": "assistant", "content": output},
        ]

        texto_formatado = tokenizer.apply_chat_template(messages, tokenize=False)
        texts.append(texto_formatado)

    return {"text": texts}

dataset = dataset.map(format_prompts, batched=True)
print("Exemplo de dado formatado com os tokens especiais do LLaMA 3.2:")
print(dataset[0]["text"][:300], "...")

"""## Célula 5: Carregar Modelo com QLoRA (4-bit) e Configurar Adaptadores LoRA"""

import gc
import torch
from transformers import AutoModelForCausalLM
from peft import LoraConfig, get_peft_model
import peft.import_utils
import peft.tuners.lora.torchao

# 1. Bypassa o bug do torchao do Colab (desativa a checagem)
peft.import_utils.is_torchao_available = lambda: False
try:
    peft.tuners.lora.torchao.is_torchao_available = lambda: False
except Exception:
    pass

# 2. Limpa resquícios da memória GPU
if 'model' in locals(): del model
if 'trainer' in locals(): del trainer
torch.cuda.empty_cache()
gc.collect()

print("Carregando LLaMA 3.2 1B em FP16 nativo (GPU T4)...")
model = AutoModelForCausalLM.from_pretrained(
    MODEL_ID,
    torch_dtype=torch.float16,
    device_map="auto",
    trust_remote_code=True,
)
model.config.use_cache = False

# 3. Configura e acopla os adaptadores LoRA
peft_config = LoraConfig(
    r=16,
    lora_alpha=32,
    target_modules=["q_proj", "k_proj", "v_proj", "o_proj", "gate_proj", "up_proj", "down_proj"],
    lora_dropout=0.05,
    bias="none",
    task_type="CAUSAL_LM",
)

model = get_peft_model(model, peft_config)

print("\n Modelo pronto para treinamento em FP16 puro!")
model.print_trainable_parameters()

"""## Célula 6: Treinamento com SFTTrainer
Com 3.000 exemplos, 1 época completa representa ~375 passos de otimização (com batch efetivo de 8), levando cerca de 8 a 10 minutos na GPU T4.
"""

from trl import SFTTrainer, SFTConfig

OUTPUT_DIR = "./llama-c-specialist-lora"

sft_config = SFTConfig(
    output_dir=OUTPUT_DIR,
    dataset_text_field="text",
    max_length=512,
    per_device_train_batch_size=2,
    gradient_accumulation_steps=4,      # Batch efetivo = 8
    learning_rate=2e-4,
    num_train_epochs=1,                  # 1 época sobre os 3.000 exemplos (~375 passos)
    logging_steps=20,
    save_strategy="steps",
    save_steps=100,
    fp16=True,                           # FP16 nativo da GPU T4
    bf16=False,                          # Desativa BFloat16
    optim="paged_adamw_8bit",
    report_to="none",
)

# Como o LoRA já foi acoplado no modelo na Célula 5, passamos o model diretamente:
try:
    trainer = SFTTrainer(
        model=model,
        train_dataset=dataset,
        processing_class=tokenizer,
        args=sft_config,
    )
except TypeError:
    trainer = SFTTrainer(
        model=model,
        train_dataset=dataset,
        tokenizer=tokenizer,
        args=sft_config,
    )

print("Iniciando o treinamento do especialista em C...")
trainer.train()

# Salvar os adaptadores finais
print(f"Salvando adaptadores LoRA em '{OUTPUT_DIR}'...")
trainer.model.save_pretrained(OUTPUT_DIR)
tokenizer.save_pretrained(OUTPUT_DIR)
print("Treinamento finalizado e adaptadores salvos com sucesso!")

"""## Célula 7: Teste de Inferência com a IA Treinada!
Faça perguntas sobre a Linguagem C para testar o conhecimento do seu modelo ajustado.
"""

import torch
from transformers import AutoModelForCausalLM
from peft import PeftModel

# 1. Se acabou de treinar na mesma sessão, reutiliza o modelo do trainer (evita CUDA OOM)
if 'trainer' in locals() and hasattr(trainer, 'model'):
    print("Reutilizando modelo já carregado na GPU após o treinamento...")
    modelo_treinado = trainer.model
else:
    # 2. Se reiniciou o notebook, define o compute_dtype e recarrega os pesos salvos
    print("Carregando modelo e adaptadores LoRA salvos em disco...")
    compute_dtype = torch.bfloat16 if torch.cuda.is_bf16_supported() else torch.float16

    base_model = AutoModelForCausalLM.from_pretrained(
        MODEL_ID,
        torch_dtype=compute_dtype,
        device_map="auto",
    )
    modelo_treinado = PeftModel.from_pretrained(base_model, OUTPUT_DIR)

modelo_treinado.eval()

# Função para fazer perguntas à IA especialista em C
def perguntar_ia(pergunta: str, max_tokens: int = 200, temp: float = 0.7):
    mensagens = [
        {"role": "system", "content": "Você é um assistente especialista em Linguagem C e programação de baixo nível."},
        {"role": "user", "content": pergunta}
    ]

    inputs = tokenizer.apply_chat_template(
        mensagens,
        add_generation_prompt=True,
        return_tensors="pt",
        return_dict=True
    ).to(modelo_treinado.device)

    with torch.no_grad():
        outputs = modelo_treinado.generate(
            **inputs,
            max_new_tokens=max_tokens,
            temperature=temp,
            top_p=0.9,
            do_sample=True,
            pad_token_id=tokenizer.eos_token_id,
        )

    resposta = tokenizer.decode(outputs[0][inputs["input_ids"].shape[1]:], skip_special_tokens=True)
    return resposta.strip()

# --- Teste de Pergunta ---
pergunta = "Qual o papel central de o compilador na programacao em C?"

print("=== PERGUNTA ===")
print(pergunta)
print("\n=== RESPOSTA DA IA ESPECIALISTA ===")
print(perguntar_ia(pergunta))

